// Gemeinsame Drahtgeometrie für Kollisionen und sichtbares Modell.
export function scoopLines(radius) {
  const k = CONFIG.scoop,
    r = radius - k.inset,
    lines = [];
  for (const z of [-k.halfDepth, 0, k.halfDepth]) {
    lines.push([
      [r - k.halfWidth, k.floor, z],
      [r + k.halfWidth, k.floor, z],
    ]);
    lines.push([
      [r - k.halfWidth, k.floor, z],
      [r - k.halfWidth, k.lip, z],
    ]);
  }
  for (const x of [r - k.halfWidth, r, r + k.halfWidth])
    lines.push([
      [x, k.floor, -k.halfDepth],
      [x, k.floor, k.halfDepth],
    ]);
  return lines;
}
export function outletPath(machine, end) {
  const c = machine.center,
    r = machine.radius,
    k = CONFIG.route;
  return [
    [
      c[0] +
        Math.cos(CONFIG.scoop.outlet) *
          (r - CONFIG.ball.radius * CONFIG.apparatus.outlet.centerInsetFactor),
      c[1] +
        Math.sin(CONFIG.scoop.outlet) *
          (r - CONFIG.ball.radius * CONFIG.apparatus.outlet.centerInsetFactor),
      c[2],
    ],
    [c[0] + r + k.elbowOffset, c[1] + r * k.elbowHeight, k.elbowZ],
    [c[0] + r + k.bottomOffset, k.bottomY, k.bottomZ],
    ...(machine.radius === CONFIG.drum.radius ? [CONFIG.route.mainEntry] : []),
    end,
  ];
}
